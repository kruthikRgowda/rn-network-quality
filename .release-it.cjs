const { execFileSync } = require('node:child_process');

const hasReleaseTag =
  execFileSync('git', ['tag', '--list', 'v[0-9]*'], {
    encoding: 'utf8',
  }).trim().length > 0;

module.exports = {
  // Keep the untagged package at 0.1.0 for its first publication. Explicit
  // increments still override this value, and Conventional Commits take over
  // after the first v* tag exists.
  increment: hasReleaseTag ? undefined : false,
  git: {
    commit: true,
    commitMessage: 'chore: release ${version}',
    push: true,
    requireCleanWorkingDir: true,
    tag: true,
    tagName: 'v${version}',
  },
  github: {
    release: true,
  },
  npm: {
    publish: true,
    skipChecks: true,
  },
  plugins: {
    '@release-it/conventional-changelog': {
      header:
        '# Changelog\n\nThis file is generated by release-it from Conventional Commits.',
      infile: 'CHANGELOG.md',
      preset: 'conventionalcommits',
    },
  },
};
